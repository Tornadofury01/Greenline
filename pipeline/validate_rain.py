"""Rainfall and frost cross-check: PRISM vs NASA POWER vs GPM IMERG for our 201 fields.

Writes docs/data-validation.md (our "Validity" evidence). Reads only the per-field CSVs; no downloads.
    pipeline/.venv/Scripts/python pipeline/validate_rain.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
F = ROOT / "pipeline" / "data" / "fields"
OUT = ROOT / "docs" / "data-validation.md"
Y0, Y1 = 2008, 2025  # years all three rain datasets cover
NAMES = {"prism": "PRISM", "power": "NASA POWER", "imerg": "GPM IMERG"}


def load():
    pr = pd.read_csv(F / "prism_monthly.csv")[["fieldId", "year", "month", "precipMm"]].rename(columns={"precipMm": "prism"})
    pw = pd.read_csv(F / "power_monthly.csv")[["fieldId", "year", "month", "precipMm"]].rename(columns={"precipMm": "power"})
    im = pd.read_csv(F / "imerg_monthly.csv")[["fieldId", "year", "month", "precipMm"]].rename(columns={"precipMm": "imerg"})
    m = pr.merge(pw, on=["fieldId", "year", "month"]).merge(im, on=["fieldId", "year", "month"])
    m = m[m.year.between(Y0, Y1)].dropna()
    # Only full years for annual totals
    full = m.groupby(["fieldId", "year"]).month.transform("size") == 12
    y = m[full].groupby(["fieldId", "year"])[["prism", "power", "imerg"]].sum().reset_index()
    return m, y


def stats(df, a, b):
    """b compared with a (a = reference)."""
    d = df[b] - df[a]
    per_field = df.groupby("fieldId").apply(lambda g: g[a].corr(g[b]), include_groups=False)
    return {"n": len(df), "corr": df[a].corr(df[b]), "fieldCorrMedian": per_field.median(),
            "fieldCorrP10": per_field.quantile(0.1), "diffMm": d.mean(), "diffPct": 100 * d.mean() / df[a].mean(),
            "rmse": float(np.sqrt((d ** 2).mean())), "meanA": df[a].mean(), "meanB": df[b].mean()}


def table(df, unit):
    rows = ["| Comparison | Correlation (all) | Median per-field correlation | Worst 10% of fields | Average difference | RMSE |",
            "|---|---|---|---|---|---|"]
    for a, b in (("prism", "power"), ("prism", "imerg"), ("power", "imerg")):
        s = stats(df, a, b)
        rows.append(f"| {NAMES[b]} vs {NAMES[a]} | {s['corr']:.2f} | {s['fieldCorrMedian']:.2f} | ≤ {s['fieldCorrP10']:.2f} | "
                    f"{s['diffMm']:+.0f} {unit} ({s['diffPct']:+.0f}%) | {s['rmse']:.0f} {unit} |")
    return "\n".join(rows)


def main():
    m, y = load()
    ann = {k: y[k].mean() for k in NAMES}
    s_ip = stats(y, "prism", "imerg")
    s_pp = stats(y, "prism", "power")

    # Storm days (>= 25 mm in a day): IMERG (UTC days) vs PRISM (12:00-12:00 UTC days)
    ist = pd.read_csv(F / "imerg_storms_monthly.csv").groupby(["fieldId", "year"]).stormDays.sum().rename("imerg")
    py = pd.read_csv(F / "prism_yearly.csv").set_index(["fieldId", "year"])
    sd = pd.concat([py.stormDays.rename("prism"), ist], axis=1, join="inner").reset_index()
    sd = sd[sd.year.between(Y0, Y1)]
    sd_corr = sd.prism.corr(sd.imerg)
    sd_year = sd.groupby("year")[["prism", "imerg"]].mean()
    sd_year_corr = sd_year.prism.corr(sd_year.imerg)

    # Frost-free days: PRISM vs POWER, 1984-2025
    pwy = pd.read_csv(F / "power_yearly.csv").set_index(["fieldId", "year"])
    ff = pd.concat([py.frostFreeDays.rename("prism"), pwy.frostFreeDays.rename("power"),
                    py.lastSpringFrostDoy.rename("prismLast")], axis=1, join="inner").dropna()
    ff_diff = (ff.power - ff.prism)
    ff_corr = ff.prism.corr(ff.power)
    no_fall_power = int(pwy.frostFreeDays.isna().groupby(level="year").any().sum())

    n_fields, n_years = y.fieldId.nunique(), y.year.nunique()
    ya, yb = int(y.year.min()), int(y.year.max())
    reg = y.groupby("year")[list(NAMES)].mean()
    dry = {k: int(reg[k].idxmin()) for k in NAMES}
    wet = {k: int(reg[k].idxmax()) for k in NAMES}
    rank2011 = {k: int(reg[k].rank()[2011]) for k in NAMES}
    txt = f"""# Data validation: does the weather data agree?

*Generated by `pipeline/validate_rain.py` from the per-field CSVs. Re-run it after a data refresh.*

Greenline uses three rainfall datasets. Two are NASA products we depend on: **NASA POWER** (~50 km, long record
back to 1984) and **GPM IMERG** (~11 km satellite rain, from 2008 in our data). We checked both against
**PRISM** (4 km, Oregon State University). PRISM is built from thousands of rain gauges and weather stations, so it's
the closest thing to "ground truth" on a grid for the U.S.

**Sample:** {n_fields} North Texas fields. Annual: {ya}–{yb} ({n_years} full years, {len(y):,} field-years). Monthly: {Y0}–{Y1}, {len(m):,} field-months
(the IMERG final product we use ends in {int(m.year.max())}-{int(m[m.year == m.year.max()].month.max()):02d}, so {Y1} is monthly only).
Each dataset is read at the field's location (the coarse pixel the field sits in).

## Annual rainfall

Average annual rain: PRISM **{ann['prism']:.0f} mm**, POWER **{ann['power']:.0f} mm**, IMERG **{ann['imerg']:.0f} mm**
({ann['prism'] / 25.4:.1f} / {ann['power'] / 25.4:.1f} / {ann['imerg'] / 25.4:.1f} inches).

{table(y, "mm")}

## Monthly rainfall

{table(m, "mm")}

## Heavy-rain days (≥ 25 mm, about 1 inch, in a day)

| | PRISM | IMERG |
|---|---|---|
| Average days per year | {sd.prism.mean():.1f} | {sd.imerg.mean():.1f} |

IMERG counts **{100 * (sd.imerg.mean() / sd.prism.mean() - 1):+.0f}%** heavy-rain days compared with PRISM. Field-year correlation: {sd_corr:.2f}. Year-to-year
correlation of the regional average: {sd_year_corr:.2f}. Caveat: PRISM "days" run 12:00–12:00 UTC (≈ 7 am–7 am local)
and IMERG days run midnight–midnight UTC, so one storm can be split differently.

## Frost-free season (last spring frost to first fall frost, Tmin ≤ 0 °C)

PRISM vs POWER, 1984–2025, {len(ff):,} field-years: correlation {ff_corr:.2f}. On average, POWER's season is
**{ff_diff.mean():+.0f} days** longer than PRISM's (median {ff_diff.median():+.0f}). PRISM's average season is {ff.prism.mean():.0f} days and POWER's is {ff.power.mean():.0f}.
POWER found no fall frost at all in {no_fall_power} year(s), so the frost-free season can't be computed for those years.

## What this means

- **Year-to-year rain is trustworthy.** Both NASA datasets track the gauge-based reference closely for annual
  totals (correlation {s_pp['corr']:.2f} for POWER, {s_ip['corr']:.2f} for IMERG). Driest year ({ya}–{yb}, regional average): PRISM {dry['prism']},
  POWER {dry['power']}, IMERG {dry['imerg']} (2011 ranks #{rank2011['prism']}, #{rank2011['power']}, #{rank2011['imerg']} driest). Wettest year: PRISM {wet['prism']}, POWER {wet['power']}, IMERG {wet['imerg']}.
- **Totals are slightly off.** Compared with PRISM, POWER reads {s_pp['diffPct']:+.0f}% and IMERG {s_ip['diffPct']:+.0f}% on annual rain. POWER runs dry, so
  rain amounts shown from POWER should be read as approximate (about ±10%).
- **Single months at single fields are noisier.** A typical month is off by about {stats(m, 'prism', 'imerg')['rmse']:.0f} mm, and POWER's 50 km cells blur
  local thunderstorms. That's one reason the weather-stress model (model 2) is weak and is shown only as a low-confidence signal.
- **Heavy-rain days:** IMERG and PRISM agree on the average count ({sd.imerg.mean():.1f} vs {sd.prism.mean():.1f} days a year), so the earlier worry that IMERG overcounts
  storm days (MODELS.md, caveat 11, which compared it with POWER) is not supported. For a single field in a single year they agree less well (r = {sd_corr:.2f}).
- **Not fully independent.** IMERG's monthly product is adjusted with gauge data (GPCC), and POWER's rain is
  bias-corrected with gauge analyses. Good agreement is consistency evidence, not proof from a separate source.
  Next step: CoCoRaHS volunteer gauges (see `datasets.md`, Future additions).
"""
    OUT.write_text(txt, encoding="utf-8")
    print(txt)


if __name__ == "__main__":
    main()
