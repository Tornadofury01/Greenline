"""Build one self-contained script per account: standalone/accountN.py.

Each file holds config, the job list for that account only, and all dataset code, so a teammate can run it anywhere
(a Colab cell, or `python accountN.py` with earthengine-api installed) without the rest of this folder.

  python make_standalone.py 5 6
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "standalone"

TEMPLATE = '''"""Field Shift v2: Earth Engine exports for ACCOUNT {n} of {total} (North Texas, {njobs} jobs, ~{hours:.1f} h of EE task time).

Self-contained: no other files needed.
  1. Set PROJECT below to account {n}'s Cloud project id (Earth Engine API enabled, registered noncommercial).
  2. Run it:  Colab -> paste into one cell and run.  Local -> pip install earthengine-api, then python account{n}.py
     It asks you to sign in with account {n}'s Google account, then submits the jobs (takes a few minutes).
  3. Check progress any time:  python account{n}.py --status   (or set STATUS_ONLY = True in Colab)

Results: CSV files in a Drive folder "{folder}" in THIS account's My Drive. Share that folder with the team lead.
Safe to rerun: jobs already queued, running or done are skipped; failed ones are resubmitted.
Generated by v2/ee_exports/make_standalone.py from assignments.json. Don't edit the job list by hand.
"""
PROJECT = "{project}"
STATUS_ONLY = False

import json, sys, time, types

_SOURCES = {sources}
JOBS = json.loads({jobs!r})


def _load_modules():
    for name in ("config", "jobs", "datasets"):
        m = types.ModuleType(name)
        sys.modules[name] = m
        exec(compile(_SOURCES[name], name + ".py", "exec"), m.__dict__)


def _existing():
    import ee
    out = {{}}
    for op in ee.data.listOperations():
        md = op.get("metadata", {{}})
        d, st = md.get("description"), md.get("state")
        if d and (d not in out or st in ("PENDING", "RUNNING", "SUCCEEDED")):
            out[d] = (st, op.get("error", {{}}).get("message"))
    return out


def main():
    import ee
    if "PUT-" in PROJECT:
        sys.exit("Set PROJECT at the top of this file to account {n}'s Cloud project id.")
    try:
        ee.Initialize(project=PROJECT)
    except Exception:
        ee.Authenticate()
        ee.Initialize(project=PROJECT)
    _load_modules()
    import config
    from jobs import Job
    from datasets import build

    have = _existing()
    names = [d["name"] for d in JOBS]
    if STATUS_ONLY or "--status" in sys.argv:
        from collections import Counter
        st = Counter(have.get(n, ("NOT SUBMITTED", None))[0] for n in names)
        print(f"account {n}: {{len(names)}} jobs:", dict(st))
        for nm in names:
            s, err = have.get(nm, (None, None))
            if s == "FAILED":
                print("  FAILED", nm, err)
        return

    ee.data.getAsset(config.FIELDS_ASSET)   # fails here if the shared field table isn't readable
    todo = [Job.from_dict(d) for d in JOBS if have.get(d["name"], (None,))[0] not in ("PENDING", "RUNNING", "SUCCEEDED")]
    print(f"account {n} ({{PROJECT}}): {{len(JOBS)}} jobs, {{len(JOBS) - len(todo)}} already queued or done, {{len(todo)}} to submit")
    for i, j in enumerate(todo, 1):
        try:
            fc, sel = build(j)
            ee.batch.Export.table.toDrive(collection=fc, description=j.name, folder=config.DEST["folder"],
                                          fileNamePrefix=j.name, fileFormat="CSV", selectors=sel).start()
            print(f"  {{i}}/{{len(todo)}} started {{j.name}}")
        except Exception as e:
            print(f"  {{i}}/{{len(todo)}} FAILED to start {{j.name}}: {{e}}")
            if "too many" in str(e).lower() or "quota" in str(e).lower():
                print("  queue limit reached: rerun later")
                break
        time.sleep(0.3)
    print("done submitting. Tasks run on Google's servers; this machine can be closed.")


main()
'''


def main():
    plan = json.loads((HERE / "assignments.json").read_text())
    accounts = json.loads((HERE / "accounts.json").read_text()) if (HERE / "accounts.json").exists() else {}
    sources = {m: (HERE / f"{m}.py").read_text() for m in ("config", "jobs", "datasets")}
    import config
    OUT.mkdir(exist_ok=True)
    for n in sys.argv[1:]:
        jobs = plan["accounts"][n]
        jobs.sort(key=lambda d: (d["tier"], -d["minutes"], d["name"]))
        project = accounts.get(n, {}).get("project") or f"PUT-ACCOUNT-{n}-PROJECT-ID-HERE"
        text = TEMPLATE.format(n=n, total=plan["nAccounts"], njobs=len(jobs), hours=sum(d["minutes"] for d in jobs) / 60,
                               folder=config.DEST["folder"], project=project,
                               sources="{\n" + "".join(f" {k!r}: {v!r},\n" for k, v in sources.items()) + "}",
                               jobs=json.dumps(jobs, separators=(",", ":")))
        p = OUT / f"account{n}.py"
        p.write_text(text)
        print(f"wrote {p.relative_to(HERE)}: {len(jobs)} jobs, project {project}")


if __name__ == "__main__":
    main()
